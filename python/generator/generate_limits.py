#!/usr/bin/env python3
"""Generate python/slackblocks/_limits.py from spec/limits.json.

The wheel and sdist are built from python/ and cannot read spec/ at runtime, so every
limit is written out as a module-level constant named after its dotted path, e.g.
button.url.max_length becomes BUTTON_URL_MAX_LENGTH.

Usage:
    python3 python/generator/generate_limits.py
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import TYPE_CHECKING, Any

if TYPE_CHECKING:
    from collections.abc import Iterator

ROOT = Path(__file__).resolve().parents[2]
LIMITS = ROOT / "spec/limits.json"
OUTPUT = ROOT / "python/slackblocks/_limits.py"
HEADER = '''\
# Generated by python/generator/generate_limits.py from spec/limits.json. Do not edit.
"""Slack Block Kit limits from spec/limits.json, the normative limit registry."""
'''


def leaves(node: dict[str, Any], prefix: str = "") -> Iterator[tuple[str, int | float]]:
    for key, value in node.items():
        path = f"{prefix}.{key}" if prefix else key
        if isinstance(value, dict):
            yield from leaves(value, path)
        elif isinstance(value, int | float) and not isinstance(value, bool):
            yield path, value
        else:
            raise TypeError(f"{path}: expected a number, got {value!r}")


def render(limits: dict[str, Any]) -> str:
    lines = [HEADER]
    paths: dict[str, str] = {}
    for path, value in leaves(limits):
        name = path.replace(".", "_").upper()
        if name in paths:
            raise ValueError(f"{path} and {paths[name]} both map to {name}")
        paths[name] = path
        lines.append(f"# {path}\n{name} = {value!r}")
    return "\n".join(lines) + "\n"


def main() -> None:
    limits = json.loads(LIMITS.read_text(encoding="utf-8"))
    OUTPUT.write_text(render(limits), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
