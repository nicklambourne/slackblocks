# Read Erlang's executable-line data without letting generated wrappers inflate the handwritten score.
alias Slackblocks.Test.ApiAudit
Mix.ensure_application!(:tools)
:cover.start()
:ok = :cover.import(~c"cover/slackblocks.coverdata")
:ok = ApiAudit.check!()
modules = ApiAudit.modules()
covered = MapSet.new(:cover.imported_modules())
expected = MapSet.new(modules)

unless MapSet.subset?(expected, covered),
  do:
    raise(
      "Missing production modules from coverage: #{inspect(MapSet.difference(expected, covered))}"
    )

{:result, all_lines, []} = :cover.analyse(modules, :coverage, :line)
by_module = Enum.group_by(all_lines, fn {{module, _}, _} -> module end)

rows =
  for module <- modules do
    source = module.module_info(:compile)[:source] |> List.to_string()

    generated =
      source |> File.read!() |> String.starts_with?("# Generated by generator/generate.py.")

    lines = Map.get(by_module, module, [])

    {hit, missed} =
      Enum.reduce(lines, {0, 0}, fn {{_, line}, {h, m}}, {hits, misses} ->
        if line > 0, do: {hits + h, misses + m}, else: {hits, misses}
      end)

    %{module: inspect(module), generated: generated, hit: hit, missed: missed}
  end

report = fn rows ->
  hit = Enum.sum(Enum.map(rows, & &1.hit))
  total = hit + Enum.sum(Enum.map(rows, & &1.missed))
  %{hit: hit, total: total, percent: if(total == 0, do: 100.0, else: 100.0 * hit / total)}
end

handwritten = Enum.reject(rows, & &1.generated)

summary = %{
  handwritten: report.(handwritten),
  total: report.(rows),
  modules: Enum.sort_by(rows, & &1.module)
}

File.write!("cover/summary.json", Jason.encode!(summary, pretty: true) <> "\n")

IO.puts(
  "Handwritten executable lines: #{summary.handwritten.hit}/#{summary.handwritten.total} (#{Float.round(summary.handwritten.percent, 2)}%)"
)

IO.puts(
  "All production executable lines: #{summary.total.hit}/#{summary.total.total} (#{Float.round(summary.total.percent, 2)}%)"
)

if summary.handwritten.percent < 90.0,
  do: raise("Handwritten executable-line coverage is below 90%")
