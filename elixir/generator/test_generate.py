"""Regression probes for the generated-file ownership boundary."""

import importlib.util
import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path

PACKAGE = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("generate", PACKAGE / "generator/generate.py")
generator = importlib.util.module_from_spec(spec)
spec.loader.exec_module(generator)


class GeneratorTest(unittest.TestCase):
    def test_literal_escapes_interpolation_and_strings(self):
        self.assertEqual(generator.literal('a#{danger}"\\\n'), '"a\\#{danger}\\"\\\\\\n"')
        self.assertEqual(generator.literal(20000), "20_000")

    def test_missing_changed_and_obsolete_output_fail(self):
        scratch = "/Volumes/Scratch" if Path("/Volumes/Scratch").is_dir() else None
        with tempfile.TemporaryDirectory(prefix="slackblocks-generator-test-", dir=scratch) as tmp:
            root = Path(tmp)
            shutil.copytree(PACKAGE.parent / "spec", root / "spec")
            shutil.copytree(
                PACKAGE / "generator",
                root / "elixir/generator",
                ignore=shutil.ignore_patterns("__pycache__"),
            )
            shutil.copytree(PACKAGE / "design", root / "elixir/design")
            shutil.copytree(PACKAGE / "lib", root / "elixir/lib")
            command = ["python3", str(root / "elixir/generator/generate.py"), "--check"]
            subprocess.run(command, check=True, capture_output=True)
            target = root / "elixir/lib/slackblocks/blocks/section.ex"
            original = target.read_text()
            target.unlink()
            self.assertNotEqual(subprocess.run(command, capture_output=True).returncode, 0)
            target.write_text(original + "\n# stale\n")
            self.assertNotEqual(subprocess.run(command, capture_output=True).returncode, 0)
            target.write_text(original)
            (root / "elixir/lib/slackblocks/obsolete.ex").write_text(
                "# Generated by generator/generate.py.\n"
            )
            self.assertNotEqual(subprocess.run(command, capture_output=True).returncode, 0)


if __name__ == "__main__":
    unittest.main()
