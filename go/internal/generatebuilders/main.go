package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

const generatedFile = "concrete_builders_gen.go"

type methodSpec struct {
	comment string
	params  string
	args    string
}

func main() {
	root, err := os.Getwd()
	must(err)

	registryData, err := os.ReadFile(filepath.Join(root, "internal", "builder_methods.json"))
	must(err)
	registry := map[string][]string{}
	must(json.Unmarshal(registryData, &registry))

	methods := loadMethods(root)
	blockConstructors := loadConstructors(filepath.Join(root, "blocks.go"))
	constructors := make([]string, 0, len(registry))
	for constructor := range registry {
		constructors = append(constructors, constructor)
	}
	sort.Strings(constructors)

	var output bytes.Buffer
	output.WriteString("// Code generated by go generate; DO NOT EDIT.\n\n")
	output.WriteString("package slackblocks\n\n")
	for _, constructor := range constructors {
		typeName := strings.TrimPrefix(constructor, "New") + "Builder"
		embeddedType := "concreteBuilder"
		factory := "newConcreteBuilder"
		if blockConstructors[constructor] {
			embeddedType = "slackBlockBuilder"
			factory = "newSlackBlockBuilder"
		}
		fmt.Fprintf(&output, "// %s is the concrete fluent builder returned by %s.\n", typeName, constructor)
		fmt.Fprintf(&output, "type %s struct { *%s }\n\n", typeName, embeddedType)
		fmt.Fprintf(&output, "func new%s(core *builder) *%s {\n", typeName, typeName)
		fmt.Fprintf(&output, "\treturn &%s{%s: %s(core)}\n", typeName, embeddedType, factory)
		output.WriteString("}\n\n")

		for _, methodName := range registry[constructor] {
			method, ok := methods[methodName]
			if !ok {
				panic(fmt.Sprintf("%s references unknown builder method %s", constructor, methodName))
			}
			if method.comment != "" {
				output.WriteString(method.comment)
				if !strings.HasSuffix(method.comment, "\n") {
					output.WriteByte('\n')
				}
			}
			fmt.Fprintf(&output, "func (b *%s) %s%s *%s {\n", typeName, methodName, method.params, typeName)
			fmt.Fprintf(&output, "\tb.core.%s(%s)\n", methodName, method.args)
			output.WriteString("\treturn b\n}\n\n")
		}
	}

	formatted, err := format.Source(output.Bytes())
	must(err)
	must(os.WriteFile(filepath.Join(root, generatedFile), formatted, 0o644))
}

func loadConstructors(path string) map[string]bool {
	set := token.NewFileSet()
	file, err := parser.ParseFile(set, path, nil, 0)
	must(err)

	constructors := map[string]bool{}
	for _, declaration := range file.Decls {
		function, ok := declaration.(*ast.FuncDecl)
		if !ok || function.Recv != nil || !function.Name.IsExported() {
			continue
		}
		name := function.Name.Name
		if strings.HasPrefix(name, "New") {
			constructors[name] = true
		}
	}
	return constructors
}

func loadMethods(root string) map[string]methodSpec {
	set := token.NewFileSet()
	methods := map[string]methodSpec{}
	entries, err := os.ReadDir(root)
	must(err)
	for _, entry := range entries {
		name := entry.Name()
		if entry.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") || name == generatedFile {
			continue
		}
		file, err := parser.ParseFile(set, filepath.Join(root, name), nil, parser.ParseComments)
		must(err)
		for _, declaration := range file.Decls {
			function, ok := declaration.(*ast.FuncDecl)
			if !ok || function.Recv == nil || len(function.Recv.List) != 1 || receiverName(function.Recv.List[0].Type) != "builder" {
				continue
			}
			methods[function.Name.Name] = methodSpec{
				comment: commentText(function.Doc),
				params:  strings.TrimPrefix(expression(set, &ast.FuncType{Params: function.Type.Params}), "func"),
				args:    callArguments(function.Type.Params),
			}
		}
	}
	return methods
}

func receiverName(expression ast.Expr) string {
	if pointer, ok := expression.(*ast.StarExpr); ok {
		expression = pointer.X
	}
	if identifier, ok := expression.(*ast.Ident); ok {
		return identifier.Name
	}
	return ""
}

func callArguments(params *ast.FieldList) string {
	if params == nil {
		return ""
	}
	arguments := []string{}
	for _, field := range params.List {
		_, variadic := field.Type.(*ast.Ellipsis)
		for _, name := range field.Names {
			argument := name.Name
			if variadic {
				argument += "..."
			}
			arguments = append(arguments, argument)
		}
	}
	return strings.Join(arguments, ", ")
}

func expression(set *token.FileSet, node any) string {
	var output bytes.Buffer
	must(printer.Fprint(&output, set, node))
	return output.String()
}

func commentText(group *ast.CommentGroup) string {
	if group == nil {
		return ""
	}
	var output strings.Builder
	for _, comment := range group.List {
		output.WriteString(comment.Text)
		output.WriteByte('\n')
	}
	return output.String()
}

func must(err error) {
	if err != nil {
		panic(err)
	}
}
