#!/usr/bin/env python3
"""Generate native PHP values directly from the shared model, limits and vocabulary."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PHP = ROOT / 'php'
HEADER = '<?php\n\ndeclare(strict_types=1);\n\n// Generated by php/generator/generate.py. Do not edit.\n\nnamespace Slackblocks;\n\n'
KINDS = {'string','boolean','int','long','double','number','enum','map','style','object','text','list','rows','textList','stringList'}

def literal(value):
    if value is None: return 'null'
    if value is True: return 'true'
    if value is False: return 'false'
    if isinstance(value, str): return "'" + value.replace('\\', '\\\\').replace("'", "\\'") + "'"
    if isinstance(value, list): return '[' + ', '.join(map(literal, value)) + ']'
    if isinstance(value, dict): return '[' + ', '.join(literal(k) + ' => ' + literal(v) for k,v in value.items()) + ']'
    return repr(value)

def enum_case(name): return ''.join(part.title() for part in name.split('_'))

def signature(field, parameter=False):
    kind = field['kind']
    if kind not in KINDS: raise ValueError(f'unknown field kind: {kind}')
    base = {'string':'string','boolean':'bool','int':'int','long':'int','double':'int|float','number':'int|float','map':'JsonObject','style':'RichTextStyle','list':'array','rows':'array','textList':'array','stringList':'array'}.get(kind, field.get('type'))
    if kind == 'text' and parameter: base += '|string'
    if not field.get('required'): base += '|null'
    return base

def doc_type(field, parameter=False):
    kind=field['kind']; target=field.get('type','string')
    base={'list':f'list<{target}>','rows':f'list<list<{target}>>','textList':f'list<{target}|string>' if parameter else f'list<{target}>','stringList':'list<string>'}.get(kind)
    return (base + ('|null' if not field.get('required') else '')) if base else signature(field,parameter)

def generate(model, limits, vocab, spec_version):
    output={}
    for interface in model['interfaces']:
        name=interface['name']; parent='Element' if name=='InputElement' else '\\JsonSerializable'
        description=interface['description'].replace(" accepted directly by Slack's official Java SDK",'')
        output[f'src/{name}.php']=HEADER+f'/** {description} */\ninterface {name} extends {parent} {{}}\n'
    for enum in model['enums']:
        lines=[HEADER+f"/** {enum['description']} */\nenum {enum['name']}: string\n{{"]
        for c in enum['constants']: lines += [f"    /** {c['description']} */",f"    case {enum_case(c['name'])} = {literal(c['wire'])};"]
        output[f"src/{enum['name']}.php"]='\n'.join(lines)+'\n}\n'
    enums={e['name']:e for e in model['enums']}
    for t in model['types']:
        name=t['name']; fields=t['fields']; defaults=t['defaults']
        roles=list(t['implements'])
        if t['package'] in ['block','element']: roles.insert(0,'Block' if t['package']=='block' else 'Element')
        lines=[HEADER+'/**',f" * {t['description']}",f" * @see {t['docUrl']}"]
        for rule in t['rules']: lines.append(' * '+rule)
        lines += [' */',f"final readonly class {name} extends Value"+(' implements '+', '.join(roles) if roles else ''),'{' ]
        for f in fields:
            lines += [f"    /** {f['description']}\n     * @var {doc_type(f)}\n     */",f"    public {signature(f)} ${f['method']};",'']
        ordered=sorted(fields,key=lambda f:not(f.get('required') and f['wire'] not in defaults))
        lines += ['    /**']+[f"     * @param {doc_type(f,True)} ${f['method']} {f['description']}" for f in ordered]+['     * @param JsonObject|null $extensions Additional JSON fields; modeled names and type are reserved.','     */','    public function __construct(']
        for f in ordered:
            default=''
            if f['wire'] in defaults:
                val=defaults[f['wire']]
                if f['kind']=='enum': val=f["type"]+'::'+next(enum_case(c['name']) for c in enums[f['type']]['constants'] if c['wire']==val)
                else: val=literal(val)
                default=' = '+val
            elif not f.get('required'): default=' = null'
            lines.append(f"        {signature(f,True)} ${f['method']}{default},")
        lines += ['        ?JsonObject $extensions = null,','    ) {']
        for f in fields:
            key=f['method']; val='$'+key
            if f['kind']=='text': val=f"is_string(${key}) ? new {'PlainText' if f.get('coerce')=='plain_text' else 'MarkdownText'}(${key}) : ${key}"
            if f['kind']=='textList':
                cls='PlainText' if f.get('coerce')=='plain_text' else 'MarkdownText'
                val=f"${key} === null ? null : array_map(static fn({f['type']}|string $item): {f['type']} => is_string($item) ? new {cls}($item) : $item, ${key})"
            if name=='Attachment' and key=='color': val="$color !== null && preg_match('/\\A[0-9a-fA-F]{6}\\z/', $color) === 1 ? '#' . $color : $color"
            lines.append(f'        $this->{key} = {val};')
        lines += ['        parent::__construct($extensions);','    }']
        if name=='Workflow': lines += ['','    /** Builds a workflow trigger from a Slack workflow URL. */','    public static function fromUrl(string $url): self','    {','        return new self(trigger: new Trigger(url: $url));','    }']
        lines += ['}','']
        output[f'src/{name}.php']='\n'.join(lines)
    flat={}
    def walk(node,prefix=''):
        for key,val in node.items():
            path=f'{prefix}.{key}' if prefix else key
            if isinstance(val,dict):walk(val,path)
            else:flat[path]=val
    walk(limits)
    schema='<?php\n\ndeclare(strict_types=1);\n\n// Generated by php/generator/generate.py. Do not edit.\n\nnamespace Slackblocks\\Internal;\n\n/** @internal Shared model metadata used by checked ingress and validation. */\nfinal class Schema\n{\n'
    for key,val in [('TYPES',{t['name']:t for t in model['types']}),('LIMITS',flat),('VOCABULARY',vocab)]:
        schema+=f'    public const {key} = '+literal(val)+';\n'
    output['src/Internal/Schema.php']=schema+'}\n'
    output['generated/reference.json']=json.dumps({'spec_version':spec_version,'types':model['types'],'interfaces':model['interfaces'],'enums':model['enums']},indent=2)+'\n'
    output['generated/files.json']=json.dumps(sorted([*output,'generated/files.json']),indent=2)+'\n'
    return output

def main():
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    read=lambda name:json.loads((ROOT/'spec'/name).read_text())
    output=generate(read('model.json'),read('limits.json'),read('vocabulary.json'),read('manifest.json')['spec_version'])
    expected=set(output); actual={str(p.relative_to(PHP)) for p in (PHP/'src').rglob('*.php') if '// Generated by php/generator/generate.py.' in p.read_text()}
    actual|={str(p.relative_to(PHP)) for p in (PHP/'generated').glob('*') if p.is_file()}
    stale=actual-expected
    if args.check:
        dirty=[name for name,content in output.items() if not (PHP/name).exists() or (PHP/name).read_text()!=content]
        if dirty or stale:raise SystemExit('Generated PHP differs: '+', '.join(sorted(set(dirty)|stale)))
    else:
        for name in stale:(PHP/name).unlink()
        for name,content in output.items():
            path=PHP/name;path.parent.mkdir(parents=True,exist_ok=True);path.write_text(content)
    print(f'{len(output)} generated PHP files verified' if args.check else f'Generated {len(output)} PHP files')

if __name__=='__main__':main()
